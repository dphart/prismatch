'use strict';
const assert=require('node:assert/strict'),R=require('./round-offers.js');
const data=require('../../Assets/Resources/Content/prismatch.json');
const level=data.levels.find(l=>l.number===2),before=JSON.stringify(data);
const report=R.overview(level,data.powers);
assert(report.powerCount>44);
assert(report.families.length>5);
for(const offer of level.roundOffers)assert.deepEqual(offer.slots[0].filters,{animal:'include'});
assert.equal(level.roundOffers.length,level.rounds);
assert.equal(level.roundDrafts.length,0);
assert.equal(level.starters.length,0);
assert.deepEqual(report.repeatedPools,[[2,3,4]]);
assert.deepEqual(report.families.find(f=>f.name==='Animal Double').rounds,[1,2,3,4]);
assert.deepEqual(report.families.find(f=>f.name==='Welcome Animal').rounds,[1,2,3,4]);
assert.equal(report.singleFamilySlots.length,0);
const double=data.powers.find(p=>p.name==='Duck Double');
const changed={...level,roundOffers:level.roundOffers.map(o=>o.round===3?{round:3,label:'Only this power',slots:[{mode:'powers',count:1,powerIds:[double.id]}]}:o)};
const custom=R.overview(changed,data.powers);
assert.deepEqual(custom.rounds[2].powers.map(p=>p.id),[double.id],'Round overrides must replace the inherited pool.');
assert.deepEqual(custom.repeatedPools,[[2,4]]);
assert(custom.singleFamilySlots.some(s=>s.round===3));
const fallback=R.overview({...level,rounds:1,starters:[],rewards:[],roundDrafts:[],roundOffers:[]},data.powers);
assert.equal(fallback.rounds[0].approximate,true);
const noDisabled=R.overview({...level,rounds:1},data.powers.map(p=>({...p,enabled:false})));
assert.equal(noDisabled.powerCount,0);
assert.equal(JSON.stringify(data),before,'Analysis must not change authored offers.');
console.log('PASS Level variety counts mechanics, flags repeated pools and single-family groups, honors overrides and preserves game data.');
