'use strict';
const assert=require('node:assert/strict'),M=require('./model.js');
const catalog=require('../../Assets/Resources/Content/prismatch.json');
const before=JSON.stringify(catalog.powers),families=M.condensePowers(catalog.powers);
const doubles=families.find(f=>f.name==='Animal Double');
assert.equal(doubles.members.length,10);
assert.equal(doubles.description,'Matches with Animal double their base points.');
assert.equal(new Set(doubles.members.map(p=>p.id)).size,10);
assert.equal(families.reduce((sum,f)=>sum+f.members.length,0),catalog.powers.length);
assert.equal(JSON.stringify(catalog.powers),before,'Grouping must never modify saved powers.');
assert.equal(families.filter(f=>f.power.type==='AnimalPairPower').length,3);
assert(families.some(f=>f.name==='Animal Growth (Points)'));
assert(families.some(f=>f.name==='Animal Growth (Multiplier)'));
const growth=catalog.powers.filter(p=>p.type==='IconTypeStreakGivesBasePointsOrMulti'&&p.parameters.BasePoints>0);
const changed=structuredClone(growth);changed[0].parameters.BasePoints++;
assert.equal(M.condensePowers(changed).length,2,'Different tuning must remain separate.');
const disabled=structuredClone(doubles.members);disabled[0].enabled=false;
assert.equal(M.condensePowers(disabled).length,2,'Availability differences must remain visible.');
const scoped=structuredClone(doubles.members);scoped[0].levelId='level-2';
assert.equal(M.condensePowers(scoped).length,2,'Level-specific copies must stay separate.');
console.log(`PASS ${catalog.powers.length} powers condense to ${families.length} entries; copies, tuning, scope, pacts and original data are preserved.`);
